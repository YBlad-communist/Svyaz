def translate(lang, key, **kwargs):
    """Return the translated string for `key`, falling back to EN and the key itself."""
    table = _TRANSLATIONS.get(lang, EN)
    value = table.get(key) or EN.get(key) or key
    if kwargs:
        try:
            return value.format(**kwargs)
        except (KeyError, IndexError):
            return value
    return value


